# 1. Объединение данных в строку
# Напишите функцию, которая принимает список любых данных (строки, числа, списки, словари) и возвращает 
# их строковое представление, объединённое через " | ". Добавьте документацию и аннотации типов для всех 
# параметров и возвращаемого значения.
# Данные:
data = [42, "hello", [1, 2, 3], {"a": 1, "b": 2}]
# Пример вывода:
# 42 | hello | [1, 2, 3] | {'a': 1, 'b': 2}

def join_data(data: list) -> str:
    """Функция объединяет элементы списка в строку через ' | '.

    Args:
        data (list): Список любых данных (строки, числа, списки, словари).

    Returns:
        str: Строковое представление элементов, объединённых через ' | '.
    """
    return " | ".join(map(str, data))

print(join_data(data))

# 2. Сумма вложенных чисел
# Напишите функцию, которая принимает список словарей, где каждый словарь содержит имя пользователя и 
# список баллов. Функция должна вернуть сумму всех чисел. Добавьте документацию и аннотации типов для 
# всех параметров и возвращаемого значения.
# Данные:
data = [
    {"name": "Alice", "scores": [10, 20, 30]},
    {"name": "Bob", "scores": [5, 15, 25]},
    {"name": "Charlie", "scores": [7, 17, 27]}
]
# Пример вывода:
# Итоговый балл: 156

def sum_scores(data: list[dict[str, list[int]]]) -> int:
    """Функция вычисляет сумму всех чисел из списков баллов в словарях.

    Args:
        data (list[dict[str, list[int]]]): Список словарей с именами пользователей и списками баллов.

    Returns:
        int: Сумма всех чисел из списков баллов.
    """
    total_score = 0
    for dic in data:
        total_score += sum(dic["scores"])
    return total_score

print(f"Итоговый балл: {sum_scores(data)}")