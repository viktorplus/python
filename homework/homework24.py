"""Напишите рекурсивную функцию, которая суммирует все числа во вложенных списках.
Пример вывода: 28"""

# deep_sun([1, [2, 3], [4, [5, 6]], 7])  -> 28
#
# Погружение (какие рекурсивные вызовы создаются):
# | Frame | nested_numbers                | вызывает рекурсию для          |
# |-------|------------------------------|---------------------------------|
# | A     | [1, [2, 3], [4, [5, 6]], 7]  | [2, 3]  (Frame B), [4,[5,6]](C) |
# | B     | [2, 3]                       | -                               |
# | C     | [4, [5, 6]]                  | [5, 6] (Frame D)                |
# | D     | [5, 6]                       | -                               |
#
# Размотка (как меняется sum внутри каждого фрейма):
# | Frame | i (по порядку)                  | действие                     | sum |
# |-------|---------------------------------|------------------------------|-----|
# | D     | 5                               | sum += 5                     | 5   |
# | D     | 6                               | sum += 6                     | 11  |
# | D     | return                          | return 11                    | 11  |
# | C     | 4                               | sum += 4                     | 4   |
# | C     | [5, 6]                          | sum += deep_sun([5,6])=11    | 15  |
# | C     | return                          | return 15                    | 15  |
# | B     | 2                               | sum += 2                     | 2   |
# | B     | 3                               | sum += 3                     | 5   |
# | B     | return                          | return 5                     | 5   |
# | A     | 1                               | sum += 1                     | 1   |
# | A     | [2, 3]                          | sum += deep_sun([2,3])=5     | 6   |
# | A     | [4, [5, 6]]                     | sum += deep_sun([4,[5,6]])=15| 21  |
# | A     | 7                               | sum += 7                     | 28  |
# | A     | return                          | return 28                    | 28  |


nested_numbers = [1, [2, 3], [4, [5, 6]], 7]


def deep_sun(nested_numbers):
    sum = 0                                   # локальная сумма ТЕКУЩЕГО списка (у каждого фрейма своя)
    for i in nested_numbers:                  # перебираем элементы текущего уровня вложенности
        if isinstance(i, list):               # если элемент тоже список — углубляемся рекурсией
            sum += deep_sun(i)                # прибавляем сумму, которую вернёт рекурсивный вызов
        else:                                 # иначе считаем, что это число
            sum += i                          # прибавляем число напрямую
    return sum                                # возвращаем сумму текущего списка (вверх, в предыдущий фрейм)


print(deep_sun(nested_numbers))               # ожидаем 28

