'''### 1. Сумма цифр числа
Напишите рекурсивную функцию, которая находит сумму всех цифр числа.
'''
# digit_sum(43197) — стек рекурсии (фреймы)
#
# Погружение (создание фреймов, каждый ждёт рекурсивный return):
# | lvl | n     | number=n%10 | new=n//10 | вызывает         |
# |-----|-------|-------------|-----------|------------------|
# | 1   | 43197 | 7           | 4319      | digit_sum(4319)  |
# | 2   | 4319  | 9           | 431       | digit_sum(431)   |
# | 3   | 431   | 1           | 43        | digit_sum(43)    |
# | 4   | 43    | 3           | 4         | digit_sum(4)     |
# | 5   | 4     | 4           | 0         | digit_sum(0)     |
# | 6   | 0     | -           | -         | return 0 (base)  |
#
# Размотка (возвраты вверх, считаем result=number+another_nums):
# | lvl | n     | another_nums (return) | result | return |
# |-----|-------|------------------------|--------|--------|
# | 5   | 4     | 0                      | 4      | 4      |
# | 4   | 43    | 4                      | 7      | 7      |
# | 3   | 431   | 7                      | 8      | 8      |
# | 2   | 4319  | 8                      | 17     | 17     |
# | 1   | 43197 | 17                     | 24     | 24     |

def digit_sum(n):
    if n == 0:                              # базовое условие выхода из рекурсии
        return 0
    number = n % 10                         # отрезаем число справа
    new_digits = n // 10                    # цифры, которые остались после отрезания
    another_nums = digit_sum(new_digits)    # отправляем остаток цифр в рекурсию
    '''Ключевой момент рекурсии: 
    Мы сейчас не считаем сумму целиком, берем последнюю цифру (number), 
    а сумму остальных цифр пусть посчитает эта же функция, но на меньшем числе (new_digits).
    Это создаёт новый фрейм (новый кадр стека) для digit_sum(new_digits)'''
    result = number + another_nums          # сложение чисел после возврата из созданных фреймов
    '''Когда рекурсивный вызов вернёт сумму оставшихся цифр (another_nums), мы прибавляем последнюю цифру.
    И возвращаем итог вверх, в предыдущий фрейм.
    '''
    return result                           # возврат результата, выход из функции

num = 43197
print(digit_sum(num))




# digit_sum2(43197) — стек рекурсии
#
# Код:
# return n % 10 + digit_sum2(n // 10)
# = (последняя цифра) + (сумма остальных цифр, посчитанная рекурсией)
#
# Погружение (создание фреймов, выражение "a + digit_sum2(...)" ещё НЕ вычислено,
# потому что нужно дождаться return из digit_sum2(...)):
# | lvl | n     | a = n%10 | new = n//10 | откладывается выражение          |
# |-----|-------|----------|-------------|----------------------------------|
# | 1   | 43197 | 7        | 4319        | 7 + digit_sum2(4319)             |
# | 2   | 4319  | 9        | 431         | 9 + digit_sum2(431)              |
# | 3   | 431   | 1        | 43          | 1 + digit_sum2(43)               |
# | 4   | 43    | 3        | 4           | 3 + digit_sum2(4)                |
# | 5   | 4     | 4        | 0           | 4 + digit_sum2(0)                |
# | 6   | 0     | -        | -           | return 0 (base case)             |
#
# Размотка (возвраты: подставляем return в отложенные выражения):
# | lvl | отложенное                 | digit_sum2(new) вернул | return |
# |-----|----------------------------|-------------------------|--------|
# | 5   | 4 + digit_sum2(0)          | 0                       | 4      |
# | 4   | 3 + digit_sum2(4)          | 4                       | 7      |
# | 3   | 1 + digit_sum2(43)         | 7                       | 8      |
# | 2   | 9 + digit_sum2(431)        | 8                       | 17     |
# | 1   | 7 + digit_sum2(4319)       | 17                      | 24     |
#
# Итог: print(digit_sum2(43197)) -> 24

def digit_sum2(n):
    if n == 0:
        return 0
    return n % 10 + digit_sum2(n // 10)


num = 43197
print(digit_sum2(num))

